import { notFound } from 'next/navigation';
import Link from 'next/link';
import ImageLightbox from '@/components/image-lightbox';
import { getAllProjects, getProjectBySlug, formatDate } from '@/lib/content';
import MDXContent from '@/components/mdx-content';
import { siteConfig, siteKeywords, breadcrumbJsonLd } from '@/lib/metadata';
import type { Metadata } from 'next';

type Props = { params: Promise<{ slug: string }> };

export const dynamicParams = false;

export function generateStaticParams() {
  return getAllProjects().map((p) => ({ slug: p.slug }));
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const project = getProjectBySlug(slug);
  if (!project) return {};
  const { title, description, metaDescription, tags } = project.frontmatter;
  // Several project descriptions run 200-300+ chars — great as the visible
  // sub-headline, but Google truncates meta/OG/Twitter descriptions around
  // 160. `metaDescription` lets a project opt into a trimmed version for
  // search-engine-facing tags while the on-page copy stays full-length.
  const metaDesc = metaDescription ?? description;
  const url = `${siteConfig.url}/projects/${slug}`;
  return {
    title,
    description: metaDesc,
    keywords: [
      ...siteKeywords,
      title,
      `Sandeep Prajapati ${title}`,
      ...(tags ?? []),
    ],
    alternates: {
      canonical: url,
      types: { 'application/rss+xml': `${siteConfig.url}/rss.xml` },
    },
    // og:image / twitter:image are generated by ./opengraph-image.tsx
    openGraph: {
      title,
      description: metaDesc,
      url,
      type: 'article',
    },
    twitter: {
      card: 'summary_large_image',
      title,
      description: metaDesc,
      creator: siteConfig.twitter,
    },
  };
}

export default async function ProjectPage({ params }: Props) {
  const { slug } = await params;
  const project = getProjectBySlug(slug);
  if (!project) notFound();

  const { title, description, date, tags, github, live, demo, image } =
    project.frontmatter;

  // "Related projects" — score every other project by the number of tags
  // it shares with this one, then take the top 3. Falls back to the most
  // recent projects when this one has no tags.
  const projectTagSet = new Set(tags ?? []);
  const related = getAllProjects()
    .filter((p) => p.slug !== slug)
    .map((p) => ({
      p,
      score: (p.frontmatter.tags ?? []).filter((t) => projectTagSet.has(t)).length,
    }))
    .sort((a, b) => {
      if (b.score !== a.score) return b.score - a.score;
      return (
        new Date(b.p.frontmatter.date).getTime() -
        new Date(a.p.frontmatter.date).getTime()
      );
    })
    .slice(0, 3)
    .map((x) => x.p);

  const projectUrl = `${siteConfig.url}/projects/${slug}`;
  const ogImage = `${projectUrl}/opengraph-image`;
  const heroImage = image ? `${siteConfig.url}${image}` : ogImage;
  const author = {
    '@type': 'Person',
    '@id': `${siteConfig.url}/#person`,
    name: 'Sandeep Prajapati',
    url: siteConfig.url,
  };

  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': live ? ['SoftwareSourceCode', 'SoftwareApplication'] : 'SoftwareSourceCode',
    name: title,
    description,
    author,
    creator: author,
    dateCreated: date,
    url: projectUrl,
    image: [heroImage, ogImage],
    ...(github ? { codeRepository: github } : {}),
    ...(live
      ? {
          // SoftwareApplication fields — makes the project eligible for
          // Google's app-style rich cards when there's a live URL to try.
          applicationCategory: 'DeveloperApplication',
          operatingSystem: 'Web',
          browserRequirements: 'Requires a modern web browser with JavaScript.',
          installUrl: live,
          offers: {
            '@type': 'Offer',
            price: '0',
            priceCurrency: 'USD',
          },
        }
      : {}),
    programmingLanguage: tags,
    keywords: tags?.join(', '),
    isPartOf: { '@id': `${siteConfig.url}/#website` },
  };

  const breadcrumb = breadcrumbJsonLd([
    { name: 'Home', path: '/' },
    { name: 'Projects', path: '/projects' },
    { name: title, path: `/projects/${slug}` },
  ]);

  return (
    <>
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
      />
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(breadcrumb) }}
      />

      <div className="max-w-2xl mx-auto px-6 py-16">
        {/* Back */}
        <Link
          href="/projects"
          className="text-sm text-neutral-400 dark:text-neutral-500 hover:text-neutral-900 dark:hover:text-neutral-100 transition-colors"
        >
          ← Projects
        </Link>

        {/* Header — <article> so Google identifies the main content block. */}
        <article className="mt-8">
          <header>
          <h1 className="text-2xl font-semibold tracking-tight text-neutral-900 dark:text-neutral-100">
            {title}
          </h1>
          <p className="mt-2 text-base text-neutral-500">{description}</p>

          <p
            className="mt-3 text-xs text-neutral-500 dark:text-neutral-400"
            itemScope
            itemType="https://schema.org/Person"
          >
            Built by{' '}
            <Link
              href="/about"
              className="underline-link"
              rel="author"
              itemProp="url"
            >
              <span itemProp="name">Sandeep Prajapati</span>
            </Link>
          </p>

          <div className="flex flex-wrap items-center gap-3 mt-4">
            <time className="text-xs text-neutral-400 dark:text-neutral-500" dateTime={date}>{formatDate(date)}</time>
            {github && (
              <a
                href={github}
                target="_blank"
                rel="noopener noreferrer"
                className="text-xs text-neutral-500 underline underline-offset-2 hover:text-neutral-900 dark:hover:text-neutral-100 transition-colors"
              >
                GitHub
              </a>
            )}
            {live && (
              <a
                href={live}
                target="_blank"
                rel="noopener noreferrer"
                className="text-xs text-neutral-500 underline underline-offset-2 hover:text-neutral-900 dark:hover:text-neutral-100 transition-colors"
              >
                Live demo
              </a>
            )}
            {demo && (
              <a
                href={demo}
                target="_blank"
                rel="noopener noreferrer"
                className="text-xs text-neutral-500 underline underline-offset-2 hover:text-neutral-900 dark:hover:text-neutral-100 transition-colors"
              >
                Video demo
              </a>
            )}
          </div>

          {tags?.length > 0 && (
            <div className="flex flex-wrap gap-1.5 mt-4">
              {tags.map((tag) => (
                <span
                  key={tag}
                  className="text-xs px-2 py-0.5 bg-neutral-100 dark:bg-neutral-800 text-neutral-500 dark:text-neutral-400 rounded-full"
                >
                  {tag}
                </span>
              ))}
            </div>
          )}
          </header>
        </article>

        {/* Hero image */}
        {image && (
          <div className="mt-8 rounded-xl overflow-hidden border border-neutral-100 dark:border-neutral-800 bg-neutral-50 dark:bg-neutral-900">
            <ImageLightbox
              src={image}
              alt={`${title} — ${description} — project by Sandeep Prajapati`}
              width={1600}
              height={900}
              priority
              sizes="(max-width: 768px) 100vw, 672px"
              className="w-full h-auto"
            />
          </div>
        )}

        {/* Divider */}
        <div className="border-t border-neutral-100 dark:border-neutral-800 my-8" />

        {/* Content */}
        <MDXContent source={project.content} />

        {/* Related projects — internal-linking + engagement signal. */}
        {related.length > 0 && (
          <section className="mt-14 pt-8 border-t border-neutral-100 dark:border-neutral-800">
            <h2 className="text-xs font-semibold uppercase tracking-widest text-neutral-400 dark:text-neutral-500 mb-4">
              Related projects
            </h2>
            <div>
              {related.map((r) => (
                <Link
                  key={r.slug}
                  href={`/projects/${r.slug}`}
                  className="group flex items-start justify-between gap-6 py-3 border-b border-neutral-100 dark:border-neutral-800 last:border-0"
                >
                  <div className="min-w-0">
                    <p className="text-sm font-medium text-neutral-900 dark:text-neutral-100 group-hover:text-neutral-500 dark:group-hover:text-neutral-400 transition-colors">
                      {r.frontmatter.title}
                    </p>
                    <p className="mt-0.5 text-sm text-neutral-500 line-clamp-1">
                      {r.frontmatter.description}
                    </p>
                  </div>
                  <span className="text-neutral-300 dark:text-neutral-600 group-hover:text-neutral-700 dark:group-hover:text-neutral-300 group-hover:translate-x-0.5 transition-all flex-shrink-0 mt-0.5">
                    →
                  </span>
                </Link>
              ))}
            </div>
          </section>
        )}

        {/* About the author — E-E-A-T signal mirroring the blog pattern. */}
        <aside className="mt-14 pt-8 border-t border-neutral-100 dark:border-neutral-800">
          <p className="text-xs font-semibold uppercase tracking-widest text-neutral-400 dark:text-neutral-500 mb-3">
            About the builder
          </p>
          <p className="text-sm text-neutral-600 dark:text-neutral-400 leading-relaxed">
            <Link
              href="/about"
              className="font-medium text-neutral-900 dark:text-neutral-100 underline-link"
            >
              Sandeep Prajapati
            </Link>{' '}
            is a Full-Stack Engineer in New Delhi building scalable AI
            products — multi-agent RAG systems and AI agents. See{' '}
            <Link href="/projects" className="underline-link">
              more projects
            </Link>{' '}
            or read the{' '}
            <Link href="/blog" className="underline-link">
              dev-log blog
            </Link>
            .
          </p>
        </aside>
      </div>
    </>
  );
}
