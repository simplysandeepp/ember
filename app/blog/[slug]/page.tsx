import { notFound } from 'next/navigation';
import Link from 'next/link';
import { getAllPosts, getPostBySlug, formatDate } from '@/lib/content';
import MDXContent from '@/components/mdx-content';
import GiscusComments from '@/components/giscus-comments';
import TableOfContents from '@/components/table-of-contents';
import { extractHeadings } from '@/lib/toc';
import { siteConfig, siteKeywords, breadcrumbJsonLd } from '@/lib/metadata';
import type { Metadata } from 'next';

type Props = { params: { slug: string } };

export const dynamicParams = false;

export function generateStaticParams() {
  return getAllPosts().map((p) => ({ slug: p.slug }));
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const post = getPostBySlug(params.slug);
  if (!post) return {};
  const { title, description, date, tags } = post.frontmatter;
  const url = `${siteConfig.url}/blog/${params.slug}`;
  return {
    title: `${title} | Sandeep Prajapati`,
    description,
    keywords: [...siteKeywords, title, ...(tags ?? [])],
    alternates: { canonical: url },
    // og:image / twitter:image are generated by ./opengraph-image.tsx
    openGraph: {
      title,
      description,
      url,
      type: 'article',
      publishedTime: date,
      authors: ['Sandeep Prajapati'],
    },
    twitter: {
      card: 'summary_large_image',
      title,
      description,
      creator: siteConfig.twitter,
    },
  };
}

export default function BlogPostPage({ params }: Props) {
  const post = getPostBySlug(params.slug);
  if (!post) notFound();

  const { title, description, date, tags } = post.frontmatter;

  // Reading time (~200 words/min) and previous/next posts.
  const words = post.content.trim().split(/\s+/).filter(Boolean).length;
  const readingTime = Math.max(1, Math.round(words / 200));
  const headings = extractHeadings(post.content);
  const allPosts = getAllPosts();
  const idx = allPosts.findIndex((p) => p.slug === params.slug);
  const newer = idx > 0 ? allPosts[idx - 1] : null;
  const older = idx >= 0 && idx < allPosts.length - 1 ? allPosts[idx + 1] : null;

  const postUrl = `${siteConfig.url}/blog/${params.slug}`;
  const ogImage = `${postUrl}/opengraph-image`;
  const author = {
    '@type': 'Person',
    '@id': `${siteConfig.url}/#person`,
    name: 'Sandeep Prajapati',
    url: siteConfig.url,
  };

  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'BlogPosting',
    headline: title,
    description,
    datePublished: date,
    dateModified: date,
    author,
    creator: author,
    publisher: author,
    wordCount: words,
    timeRequired: `PT${readingTime}M`,
    mainEntityOfPage: {
      '@type': 'WebPage',
      '@id': postUrl,
    },
    image: {
      '@type': 'ImageObject',
      url: ogImage,
      width: 1200,
      height: 630,
    },
    url: postUrl,
    keywords: tags?.join(', '),
    inLanguage: 'en',
    isPartOf: { '@id': `${siteConfig.url}/#website` },
  };

  const breadcrumb = breadcrumbJsonLd([
    { name: 'Home', path: '/' },
    { name: 'Writing', path: '/blog' },
    { name: title, path: `/blog/${params.slug}` },
  ]);

  return (
    <>
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
      />
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(breadcrumb) }}
      />

      <div className="max-w-2xl mx-auto px-6 py-16">
        {/* Back */}
        <Link
          href="/blog"
          className="text-sm text-neutral-400 dark:text-neutral-500 hover:text-neutral-900 dark:hover:text-neutral-100 transition-colors"
        >
          ← Writing
        </Link>

        {/* Header — <article> lets Google identify the main content block. */}
        <article className="mt-8">
          <header>
            <h1 className="text-2xl font-semibold tracking-tight text-neutral-900 dark:text-neutral-100 leading-snug">
              {title}
            </h1>
            <p className="mt-2 text-base text-neutral-500">{description}</p>
            <div className="flex items-center gap-4 mt-3 flex-wrap">
              <p
                className="text-xs text-neutral-500 dark:text-neutral-400"
                itemScope
                itemType="https://schema.org/Person"
              >
                By{' '}
                <Link
                  href="/about"
                  className="underline-link"
                  rel="author"
                  itemProp="url"
                >
                  <span itemProp="name">Sandeep Prajapati</span>
                </Link>
              </p>
              <span aria-hidden className="text-xs text-neutral-300 dark:text-neutral-600">·</span>
              <time
                className="text-xs text-neutral-400 dark:text-neutral-500"
                dateTime={date}
              >
                {formatDate(date)}
              </time>
              <span aria-hidden className="text-xs text-neutral-300 dark:text-neutral-600">·</span>
              <span className="text-xs text-neutral-400 dark:text-neutral-500">{readingTime} min read</span>
              {tags && tags.length > 0 && (
                <div className="flex flex-wrap gap-1.5">
                  {tags.map((tag) => (
                    <span
                      key={tag}
                      className="text-xs px-2 py-0.5 bg-neutral-100 dark:bg-neutral-800 text-neutral-500 dark:text-neutral-400 rounded-full"
                    >
                      {tag}
                    </span>
                  ))}
                </div>
              )}
            </div>
          </header>
        </article>

        {/* Table of contents (long posts only) */}
        <TableOfContents headings={headings} />

        {/* Divider */}
        <div className="border-t border-neutral-100 dark:border-neutral-800 my-8" />

        {/* Content */}
        <MDXContent source={post.content} />

        {/* Author bio — classic E-E-A-T signal. Every post ends with an
            explicit "who wrote this" byline linked to /about. */}
        <aside className="mt-14 pt-8 border-t border-neutral-100 dark:border-neutral-800">
          <p className="text-xs font-semibold uppercase tracking-widest text-neutral-400 dark:text-neutral-500 mb-3">
            About the author
          </p>
          <p className="text-sm text-neutral-600 dark:text-neutral-400 leading-relaxed">
            <Link href="/about" className="font-medium text-neutral-900 dark:text-neutral-100 underline-link">
              Sandeep Prajapati
            </Link>{' '}
            is an AI Engineer &amp; Full-Stack Developer in New Delhi,
            building production RAG pipelines and AI agents. He&apos;s
            currently an AI Software Developer Intern at{' '}
            <a href="https://drcode.ai" target="_blank" rel="noopener noreferrer" className="underline-link">
              DrCode
            </a>
            . More at{' '}
            <Link href="/projects" className="underline-link">
              /projects
            </Link>{' '}
            or{' '}
            <Link href="/about" className="underline-link">
              /about
            </Link>
            .
          </p>
        </aside>

        {/* Prev / next */}
        {(newer || older) && (
          <nav className="mt-14 pt-8 border-t border-neutral-100 dark:border-neutral-800 flex justify-between gap-6">
            {older ? (
              <Link href={`/blog/${older.slug}`} className="group max-w-[48%]">
                <span className="block text-xs text-neutral-400 dark:text-neutral-500">← Older</span>
                <span className="block text-sm text-neutral-700 dark:text-neutral-300 group-hover:text-neutral-500 dark:group-hover:text-neutral-400 transition-colors mt-1 line-clamp-2">
                  {older.frontmatter.title}
                </span>
              </Link>
            ) : (
              <span />
            )}
            {newer ? (
              <Link href={`/blog/${newer.slug}`} className="group max-w-[48%] text-right ml-auto">
                <span className="block text-xs text-neutral-400 dark:text-neutral-500">Newer →</span>
                <span className="block text-sm text-neutral-700 dark:text-neutral-300 group-hover:text-neutral-500 dark:group-hover:text-neutral-400 transition-colors mt-1 line-clamp-2">
                  {newer.frontmatter.title}
                </span>
              </Link>
            ) : (
              <span />
            )}
          </nav>
        )}

        {/* Comments */}
        <GiscusComments />
      </div>
    </>
  );
}
